import * as fs from 'node:fs';
import * as path from 'node:path';
import { Sequelize } from 'sequelize-typescript';
import { SHOP_MODELS } from '../src/database/models';

// Compares every model with the Sequelize definition of the old Server (table, columns, keys, associations). The old models are
// loaded without a database connection. Skipped once the old Server folder is gone (after the cutover).
const oldServer = path.resolve(__dirname, '..', '..', 'Server');
const oldModelsIndex = path.join(oldServer, 'models', 'index.js');

type AttributeInfo = { field: string; type: string; primaryKey: boolean; allowNull: boolean };
type ModelInfo = { table: string; paranoid: boolean; timestamps: boolean; attributes: Record<string, AttributeInfo>; associations: Record<string, string> };

// The shape of a Sequelize model that both the old (plain) and the new (sequelize-typescript) models share
interface AnyModel {
  tableName: string;
  options: { paranoid?: boolean; timestamps?: boolean };
  rawAttributes: Record<string, { field?: string; type: { key: string }; primaryKey?: boolean; allowNull?: boolean; _autoGenerated?: boolean }>;
  associations: Record<string, { associationType: string; foreignKey: string; target: { tableName: string } }>;
}

const describeModel = (model: AnyModel): ModelInfo => ({
  table: model.tableName,
  paranoid: !!model.options.paranoid,
  timestamps: model.options.timestamps !== false,
  attributes: Object.fromEntries(
    Object.entries(model.rawAttributes)
      .filter(([, def]) => !def._autoGenerated)
      .map(([name, def]) => [name, { field: def.field ?? name, type: def.type.key, primaryKey: !!def.primaryKey, allowNull: def.allowNull !== false }]),
  ),
  associations: Object.fromEntries(Object.entries(model.associations).map(([alias, a]) => [alias, `${a.associationType} ${a.foreignKey} -> ${a.target.tableName}`])),
});

const className = (key: string) => key.split('_').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');

(fs.existsSync(oldModelsIndex) ? describe : describe.skip)('models match the old Server', () => {
  const previous = { ...process.env };
  let oldModels: Record<string, AnyModel>;
  let newModels: Map<string, AnyModel>;

  beforeAll(() => {
    Object.assign(process.env, { DB_HOST: 'localhost', DB_USER: 'x', DB_PASS: 'x', DB_NAME: 'x', TOKEN_KEY: 'x' });
    const cwd = process.cwd();
    process.chdir(oldServer);
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    oldModels = require(oldModelsIndex) as Record<string, AnyModel>;
    process.chdir(cwd);

    const sequelize = new Sequelize({ dialect: 'mysql', models: SHOP_MODELS, logging: false });
    newModels = new Map(SHOP_MODELS.map((model) => [model.name, sequelize.model(model) as unknown as AnyModel]));
  });

  afterAll(() => {
    process.env = previous;
  });

  it('has a model for every model of the old Server, and no others', () => {
    const oldNames = Object.entries(oldModels).filter(([, m]) => m && m.rawAttributes).map(([key]) => className(key)).sort();
    expect([...newModels.keys()].sort()).toEqual(oldNames);
  });

  it('describes the same tables, columns, keys and associations', () => {
    const problems: string[] = [];
    for (const [key, oldModel] of Object.entries(oldModels)) {
      if (!oldModel || !oldModel.rawAttributes) continue;
      const newModel = newModels.get(className(key));
      if (!newModel) continue;
      const a = describeModel(oldModel);
      const b = describeModel(newModel);
      if (JSON.stringify(a) !== JSON.stringify(b)) {
        for (const field of ['table', 'paranoid', 'timestamps'] as const) if (a[field] !== b[field]) problems.push(`${key}: ${field} ${a[field]} != ${b[field]}`);
        for (const attr of new Set([...Object.keys(a.attributes), ...Object.keys(b.attributes)])) {
          if (JSON.stringify(a.attributes[attr]) !== JSON.stringify(b.attributes[attr])) problems.push(`${key}.${attr}: ${JSON.stringify(a.attributes[attr])} != ${JSON.stringify(b.attributes[attr])}`);
        }
        for (const assoc of new Set([...Object.keys(a.associations), ...Object.keys(b.associations)])) {
          if (a.associations[assoc] !== b.associations[assoc]) problems.push(`${key}.${assoc}: ${a.associations[assoc]} != ${b.associations[assoc]}`);
        }
      }
    }
    expect(problems).toEqual([]);
  });
});
