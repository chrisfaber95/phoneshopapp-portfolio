// Generates the TypeScript models of ServerNest from the Sequelize model definitions of the old Server
// (attributes, options and associations), so that they describe exactly the same tables:
//
//   node tools/generate-models.js          (from the ServerNest folder)
//
// Output: src/database/models/*.model.ts and index.ts. The files are generated ONCE as the starting point of each module and are
// maintained by hand afterwards (the header of every file says so); re-running the generator overwrites them. The generator reads
// the old models only; it does not connect to a database.

const fs = require('node:fs');
const path = require('node:path');

const repo = path.resolve(__dirname, '..', '..');
const { safeEnv } = require(path.join(repo, 'parity', 'safe-env'));
Object.assign(process.env, safeEnv()); // never load the real Server/.env
process.chdir(path.join(repo, 'Server'));

const old = require(path.join(repo, 'Server', 'models', 'index'));
const entries = Object.entries(old).filter(([, m]) => m && m.rawAttributes);
const outDir = path.join(repo, 'ServerNest', 'src', 'database', 'models');

const classNameOf = (key) => key.split('_').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');
const fileOf = (className) => className.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const classByModel = new Map(entries.map(([key, model]) => [model, classNameOf(key)]));

const dataType = (type) => {
    const key = type.key;
    if (key === 'STRING') return type._length && type._length !== 255 ? `DataType.STRING(${type._length})` : 'DataType.STRING';
    if (key === 'DECIMAL') return type._precision ? `DataType.DECIMAL(${type._precision}, ${type._scale ?? 0})` : 'DataType.DECIMAL';
    if (['TEXT', 'UUID', 'INTEGER', 'FLOAT', 'BOOLEAN', 'DATE', 'DATEONLY', 'TIME', 'TINYINT', 'BIGINT', 'DOUBLE'].includes(key)) return `DataType.${key}`;
    throw new Error(`unsupported type ${key}`);
};
const tsType = (type) => {
    if (['INTEGER', 'FLOAT', 'TINYINT', 'BIGINT', 'DOUBLE'].includes(type.key)) return 'number';
    if (type.key === 'BOOLEAN') return 'boolean';
    if (type.key === 'DATE') return 'Date';
    return 'string'; // STRING, TEXT, UUID, TIME, DATEONLY and DECIMAL (mysql2 returns decimals as text)
};

// Defaults that are functions in the old models and are ported here by hand
const FUNCTION_DEFAULTS = {
    'Customer.klantenkaart': {
        name: 'generateCardNumber',
        source: [
            '// 13-digit loyalty card number, as generated by the old Server',
            'const generateCardNumber = (): string => String(Math.floor(1_000_000_000_000 + Math.random() * 9_000_000_000_000));',
            '',
        ].join('\n'),
    },
};

const warnings = [];
const generated = [];

for (const [key, model] of entries) {
    const className = classNameOf(key);
    const used = new Set(['Column', 'DataType', 'Model', 'Table']);
    const imports = new Map();
    const lines = [];
    const helpers = [];

    // ---- attributes
    for (const [name, def] of Object.entries(model.rawAttributes)) {
        if (def._autoGenerated) continue; // createdAt / updatedAt / deletedAt come from the table options
        const decorators = [];
        if (def.primaryKey) { decorators.push('@PrimaryKey'); used.add('PrimaryKey'); }
        if (def.autoIncrement) { decorators.push('@AutoIncrement'); used.add('AutoIncrement'); }
        if (def.allowNull === false) { decorators.push('@AllowNull(false)'); used.add('AllowNull'); }
        const dv = def.defaultValue;
        if (dv !== undefined && dv !== null) {
            if (dv.constructor && dv.constructor.name === 'UUIDV4') { decorators.push('@Default(DataType.UUIDV4)'); used.add('Default'); }
            else if (dv.constructor && dv.constructor.name === 'NOW') { decorators.push('@Default(DataType.NOW)'); used.add('Default'); }
            else if (FUNCTION_DEFAULTS[`${className}.${name}`]) { decorators.push(`@Default(${FUNCTION_DEFAULTS[`${className}.${name}`].name})`); used.add('Default'); helpers.push(FUNCTION_DEFAULTS[`${className}.${name}`].source); }
            else if (['string', 'number', 'boolean'].includes(typeof dv)) { decorators.push(`@Default(${JSON.stringify(dv)})`); used.add('Default'); }
            else warnings.push(`${className}.${name}: default value (${typeof dv}) not generated, port it by hand`);
        }
        const type = dataType(def.type);
        decorators.push(def.field && def.field !== name ? `@Column({ type: ${type}, field: '${def.field}' })` : `@Column(${type})`);
        const nullable = !(def.primaryKey || def.allowNull === false);
        lines.push(...decorators.map((d) => `  ${d}`), `  declare ${name}: ${tsType(def.type)}${nullable ? ' | null' : ''};`, '');
    }

    // ---- associations
    for (const assoc of Object.values(model.associations)) {
        const target = classByModel.get(assoc.target);
        if (!target) { warnings.push(`${className}.${assoc.as}: target model not found`); continue; }
        if (target !== className) imports.set(target, `./${fileOf(target)}.model`);
        const opts = [`foreignKey: '${assoc.foreignKey}'`];
        if (assoc.associationType === 'BelongsTo' && assoc.targetKey) opts.push(`targetKey: '${assoc.targetKey}'`);
        if (assoc.associationType !== 'BelongsTo' && assoc.sourceKey) opts.push(`sourceKey: '${assoc.sourceKey}'`);
        if (assoc.associationType === 'BelongsToMany') { warnings.push(`${className}.${assoc.as}: BelongsToMany not generated`); continue; }
        used.add(assoc.associationType);
        const tsT = assoc.associationType === 'HasMany' ? `${target}[]` : `${target} | null`;
        lines.push(`  @${assoc.associationType}(() => ${target}, { ${opts.join(', ')} })`, `  declare ${assoc.as}: ${tsT};`, '');
    }

    // ---- table options
    const o = model.options;
    const tableOptions = [`tableName: '${model.tableName}'`, 'freezeTableName: true'];
    if (o.timestamps === false) tableOptions.push('timestamps: false');
    if (o.paranoid) tableOptions.push('paranoid: true');
    if (o.createdAt !== undefined && o.createdAt !== 'createdAt' && o.timestamps !== false) warnings.push(`${className}: custom createdAt ${o.createdAt}`);
    if (o.scopes && Object.keys(o.scopes).length) warnings.push(`${className}: named scopes not generated`);
    const scope = Object.fromEntries(Object.entries(o.defaultScope || {}).filter(([, v]) => !(v && typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length === 0)));
    const header = [];
    if (Object.keys(scope).length) {
        const parts = [];
        if (scope.attributes) parts.push(`attributes: ${JSON.stringify(scope.attributes)}`);
        if (scope.include) {
            const includes = scope.include.map((inc) => {
                const cls = classByModel.get(inc.model);
                if (cls !== className) imports.set(cls, `./${fileOf(cls)}.model`);
                return `{ model: ${cls}, as: '${inc.as}'${inc.required !== undefined ? `, required: ${inc.required}` : ''} }`;
            });
            parts.push(`include: [${includes.join(', ')}]`);
        }
        const others = Object.keys(scope).filter((k) => !['attributes', 'include'].includes(k));
        if (others.length) warnings.push(`${className}: default scope keys not generated: ${others.join(', ')}`);
        header.push(`@DefaultScope(() => ({ ${parts.join(', ')} }))`);
        used.add('DefaultScope');
    }

    const sequelizeImports = [...used].sort();
    const body = [
        '// Generated from Server/models by tools/generate-models.js, maintained by hand from here on.',
        `import { ${sequelizeImports.join(', ')} } from 'sequelize-typescript';`,
        ...[...imports].sort().map(([cls, file]) => `import { ${cls} } from '${file}';`),
        '',
        ...helpers,
        ...(helpers.length ? [''] : []),
        ...header,
        `@Table({ ${tableOptions.join(', ')} })`,
        `export class ${className} extends Model {`,
        ...lines.slice(0, -1), // drop the trailing blank line
        '}',
        '',
    ].join('\n');
    generated.push({ className, file: `${fileOf(className)}.model.ts`, body });
}

// Remove the previous output, then write the new files
fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) if (f.endsWith('.model.ts') || f === 'index.ts') fs.rmSync(path.join(outDir, f));
for (const g of generated) fs.writeFileSync(path.join(outDir, g.file), g.body);

const sorted = [...generated].sort((a, b) => a.className.localeCompare(b.className));
fs.writeFileSync(path.join(outDir, 'index.ts'), [
    '// Generated from Server/models by tools/generate-models.js, maintained by hand from here on.',
    ...sorted.map((g) => `import { ${g.className} } from './${g.file.replace(/\.ts$/, '')}';`),
    '',
    `export { ${sorted.map((g) => g.className).join(', ')} };`,
    '',
    '// Every model of the shop database, registered on the connection in AppModule',
    `export const SHOP_MODELS = [${sorted.map((g) => g.className).join(', ')}];`,
    '',
].join('\n'));

console.log(`generated ${generated.length} models into ${path.relative(repo, outDir)}`);
warnings.forEach((w) => console.log(`WARNING ${w}`));
process.exit(0);
